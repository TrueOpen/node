var executionMilestoneName = regexp.MustCompile(`(?i)goal[0-9]`)

func TestModuleSplitImportBoundaries(t *testing.T) {
	repo := "."

	assertNoImport(t, repo, filepath.Join("x", "hub"), "github.com/TrueOpen/node/x/task")
	assertNoImport(t, repo, filepath.Join("x", "task"), "github.com/TrueOpen/node/x/hub/keeper")
	assertNoImport(t, repo, filepath.Join("x", "shared"), "github.com/TrueOpen/node/x/hub")
	assertNoImport(t, repo, filepath.Join("x", "shared"), "github.com/TrueOpen/node/x/task")
	assertNoSharedBusinessSurface(t, repo, filepath.Join("x", "shared"))
}

// TestInternalBeaconProtoStaysOutsidePublicSDKModule keeps BeaconStoreState out
// of the published contract.
//
// The public side used to be a local Buf module declared in buf.yaml, and this
// test asserted internal/proto was not one of its inputs. buf.yaml went away with
// proto/: the public contract is now the pinned TrueOpen/wire release image, so
// the property is restated against that. internal/proto is generated by its own
// separate invocation from its own sources, and nothing it contains can reach a
// wire release, because this repository does not publish one.
func TestInternalBeaconProtoStaysOutsidePublicSDKModule(t *testing.T) {
	makefileBody, err := os.ReadFile("Makefile")
	if err != nil {
		t.Fatal(err)
	}
	public := string(makefileBody)
	if strings.Contains(public, "$(WIRE_IMAGE) internal/proto") ||
		strings.Contains(public, "internal/proto $(WIRE_IMAGE)") {
		t.Fatal("internal/proto must not be an input of the public generation request")
	}
	// The internal module is generated from its own sources, never from the wire
	// image, so its types cannot appear in anything a consumer downloads.
	if !strings.Contains(public, "buf generate internal/proto --template internal/proto/buf.gen.gogo.yaml") {
		t.Fatal("internal/proto must be generated from its own sources by its own invocation")
	}
	internalProto, err := os.ReadFile(filepath.FromSlash("internal/proto/hub/internal/v1/beacon_store.proto"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(internalProto), `go_package = "github.com/TrueOpen/node/x/hub/internal/types"`) {
		t.Fatal("BeaconStoreState must remain under a Go internal import boundary")
	}
	makefile, err := os.ReadFile("Makefile")
	if err != nil {
		t.Fatal(err)
	}
	for _, required := range []string{
		"buf generate internal/proto",
		"x/hub/internal/types/*.pb.go",
	} {
		if !strings.Contains(string(makefile), required) {
			t.Fatalf("Makefile is missing internal proto generation gate %q", required)
		}
	}
}

func TestCodeIdentifiersUseBusinessNames(t *testing.T) {
	walkGoFiles(t, ".", func(path string, body string) {
		if executionMilestoneName.MatchString(filepath.Base(path)) {
			t.Fatalf("%s uses an execution milestone in its filename", path)
		}
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, path, body, 0)
		if err != nil {
			t.Fatalf("%s: parse failed: %v", path, err)
		}
		ast.Inspect(file, func(node ast.Node) bool {
			identifier, ok := node.(*ast.Ident)
			if ok && executionMilestoneName.MatchString(identifier.Name) {
				t.Fatalf("%s uses execution milestone identifier %q", path, identifier.Name)
			}
			return true
		})
	})
}

func assertNoImport(t *testing.T, repo, dir, forbidden string) {
	t.Helper()
	walkGoFiles(t, filepath.Join(repo, dir), func(path string, body string) {
		if strings.Contains(body, forbidden) {
			t.Fatalf("%s imports forbidden boundary %q", path, forbidden)
		}
	})
}

// assertNoSharedBusinessSurface scans identifiers and selector expressions only,
// deliberately skipping comments and string literals. The §1.4 domain registry in
// x/shared/types has to record the contract's producer column verbatim ("Task
// Keeper", "Hub bond handler", ...), and that documentation is what lets us catch a
// single domain growing two different preimages. A doc comment naming a module does
// not give shared a business surface, so the earlier raw substring scan over the
// whole file body was a false positive that made the registry impossible to write.
// Scanning the AST is also stricter than the substring form: a domain string such as
// "TRUEOPEN_..._KEEPER_V1" no longer trips the guard either.
func assertNoSharedBusinessSurface(t *testing.T, repo, dir string) {
	t.Helper()
	forbiddenIdents := []string{"Keeper", "MsgServer", "RegisterMsgServer", "KVStore"}
	forbiddenSelectors := []string{"collections.NewMap"}

	walkGoFiles(t, filepath.Join(repo, dir), func(path string, body string) {
		fset := token.NewFileSet()
		// Mode 0 leaves comments out of the tree entirely.
		file, err := parser.ParseFile(fset, path, body, 0)
		if err != nil {
			t.Fatalf("%s: parse failed: %v", path, err)
		}
		ast.Inspect(file, func(node ast.Node) bool {
			switch typed := node.(type) {
			case *ast.SelectorExpr:
				pkg, ok := typed.X.(*ast.Ident)
				if !ok {
					return true
				}
				qualified := pkg.Name + "." + typed.Sel.Name
				for _, forbidden := range forbiddenSelectors {
					if qualified == forbidden {
						t.Fatalf("%s gives shared business surface %q", path, forbidden)
					}
				}
			case *ast.Ident:
				for _, forbidden := range forbiddenIdents {
					if strings.Contains(typed.Name, forbidden) {
						t.Fatalf("%s gives shared business surface %q (identifier %q)", path, forbidden, typed.Name)
					}
				}
			}
			return true
		})
	})
}

func walkGoFiles(t *testing.T, root string, visit func(path string, body string)) {
	t.Helper()
	if _, err := os.Stat(root); os.IsNotExist(err) {
		return
	}
	if err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".go") {
			return nil
		}
		bytes, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		visit(path, string(bytes))
		return nil
	}); err != nil {
		t.Fatal(err)
	}
}
